import { describe, expect, it } from "vitest";
import { parseFrontmatter, replaceFrontmatterField } from "./frontmatter.js";

// Все случаи ниже — не выдуманные, а те, на которых парсер уже ломался
// живьём: модели по-разному оформляют один и тот же документ.
describe("parseFrontmatter", () => {
  it("читает обычный блок в начале документа", () => {
    const doc = ["---", "статус: боевой", "b2b: false", "---", "", "# Профиль ЦА"].join("\n");
    expect(parseFrontmatter(doc)).toEqual({ статус: "боевой", b2b: false });
  });

  it("не падает на двоеточии внутри значения", () => {
    // Темы контент-плана часто выглядят как «Формат: суть», и такое значение
    // делает весь блок невалидным YAML — падает не одно поле, а документ.
    const doc = ["---", "статус: боевой", "тема: Личная история: как я пришла в профессию", "---", "", "текст"].join("\n");
    expect(parseFrontmatter(doc)).toMatchObject({
      статус: "боевой",
      тема: "Личная история: как я пришла в профессию",
    });
  });

  it("пропускает разделитель, стоящий до настоящего блока", () => {
    // Модель иногда ставит markdown-разделитель или преамбулу перед
    // frontmatter — первая пара «---» тогда обрамляет произвольный текст.
    const doc = ["Ниже документ.", "", "---", "", "```yaml", "---", "статус: черновик-рамка", "---"].join("\n");
    expect(parseFrontmatter(doc)).toEqual({ статус: "черновик-рамка" });
  });

  it("возвращает null, когда frontmatter нет вовсе", () => {
    expect(parseFrontmatter("# Просто заголовок\n\nи текст")).toBeNull();
  });

  it("возвращает null на обрывке интервью вместо документа", () => {
    // Так выглядел реальный сбой: модель ушла в диалоговый режим и вернула
    // вопрос вместо документа. Молча подставлять статус в таком случае нельзя.
    expect(parseFrontmatter("Вопрос 1 (Блок 1). Расскажите, с чего всё началось?")).toBeNull();
  });
});

describe("replaceFrontmatterField", () => {
  it("переписывает поле, не трогая остальной документ", () => {
    const doc = ["---", "статус: боевой", "b2b: false", "---", "", "# Заголовок"].join("\n");
    const updated = replaceFrontmatterField(doc, "статус", "черновик-рамка");
    expect(parseFrontmatter(updated)).toMatchObject({ статус: "черновик-рамка", b2b: false });
    expect(updated).toContain("# Заголовок");
  });

  it("оставляет документ как есть, если поля нет", () => {
    const doc = ["---", "b2b: false", "---", "", "текст"].join("\n");
    expect(replaceFrontmatterField(doc, "статус", "боевой")).toBe(doc);
  });
});
