// Извлекает готовый английский промпт из документа visual-generator или
// reels-video-generator — оба оборачивают "Готовый промпт" в ```text блок
// именно для надёжного извлечения кодом, тот же принцип, что и JSON-блок
// content-planner (см. planData.ts): перебираем все совпадения на случай
// decoy-блока раньше настоящего, берём первый непустой.
//
// Хвост документа после незакрытого блока приходится подбирать отдельно: в
// живом прогоне модель открыла ```text, дописала промпт целиком и не закрыла
// фенс, приписав в конце "-->" от html-комментария. Промпт был полный, но
// строгий разбор его не видел — клиент получал отказ «не удалось
// сгенерировать картинку», а повтор упирался в тот же документ. Терять готовый
// платный результат из-за пропущенных трёх обратных кавычек нельзя.
const TRAILING_JUNK = /(?:\s|-->|`+)+$/;

export function extractPromptBlock(document: string): string | null {
  // После ```text забираем ровно один перевод строки ([ \t]*\n, не \s*\n):
  // иначе у пустого блока обе пустые строки уходили в разделитель, закрывающий
  // фенс переставал совпадать, и совпадение растягивалось до конца следующего
  // блока — пустой decoy утаскивал за собой настоящий промпт.
  const blocks = [...document.matchAll(/```text[ \t]*\n([\s\S]*?)\n```/g)];
  for (const block of blocks) {
    const text = block[1].trim();
    if (text.length > 0) return text;
  }

  const unclosed = document.match(/```text[ \t]*\n([\s\S]*)$/);
  if (unclosed) {
    const text = unclosed[1].replace(TRAILING_JUNK, "").trim();
    if (text.length > 0) return text;
  }

  return null;
}
